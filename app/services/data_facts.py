def _freshness(latest: Quarter) -> str:
    return (f"2021년 1분기부터 {latest[0]}년 {latest[1]}분기({label(latest)})까지의 분기 데이터입니다. "
            "2026년 1·2분기는 공식 파일이 아직 없어 열린데이터광장 화면의 CSV 내려받기 자료를 썼어요. "
            "같은 방법으로 받은 2025년 자료가 공식 2025년 파일과 숫자가 모두 같은 것을 확인했어요.")


def answer_for(question: str, latest: Quarter) -> tuple[str, str] | None:
    """(주제, 답변) 또는 None. 분석 질문("성수 점포 수 알려줘", "강남 최신 분기 매출")은 건드리지 않는다."""
    for t in TOPICS:
        if not any(w in question for w in t.triggers):
            continue
        if t.asking is not None and not any(w in question for w in t.asking):
            continue
        if not t.limit and _is_analysis(question):
            continue
        return t.name, (_freshness(latest) if t.text == "{period}" else t.text)
    return None
